-- =====================================================
-- COOK-LIST: V1 - Esquema inicial
-- PostgreSQL
-- =====================================================

-- 1. ROLES
CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

-- 2. USERS
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    family_size INTEGER NOT NULL,
    birth_date DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    role_id BIGINT NOT NULL,

    CONSTRAINT fk_users_roles
        FOREIGN KEY (role_id)
        REFERENCES roles(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_users_family_size
        CHECK (family_size > 0)
);

-- 3. CATEGORY
CREATE TABLE category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

-- 4. UNITS
CREATE TABLE units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    symbol VARCHAR(20) NOT NULL
);

-- 5. INGREDIENTS
CREATE TABLE ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    unit_id BIGINT NOT NULL,

    CONSTRAINT fk_ingredients_units
        FOREIGN KEY (unit_id)
        REFERENCES units(id)
        ON DELETE RESTRICT
);

-- 6. RECIPES
CREATE TABLE recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    preparation_minutes INTEGER NOT NULL,

    CONSTRAINT fk_recipes_users
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_recipes_category
        FOREIGN KEY (category_id)
        REFERENCES category(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_recipes_preparation_minutes
        CHECK (preparation_minutes > 0)
);

-- 7. RECIPE_INGREDIENTS
CREATE TABLE recipe_ingredients (
    recipe_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    quantity NUMERIC(10, 2) NOT NULL,

    CONSTRAINT pk_recipe_ingredients
        PRIMARY KEY (recipe_id, ingredient_id),

    CONSTRAINT fk_recipe_ingredients_recipes
        FOREIGN KEY (recipe_id)
        REFERENCES recipes(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_recipe_ingredients_ingredients
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredients(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_recipe_ingredients_quantity
        CHECK (quantity > 0)
);